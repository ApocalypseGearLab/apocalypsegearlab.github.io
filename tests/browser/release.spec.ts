import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdirSync, readFileSync } from 'node:fs';

const candidates = ['ecoflow-river-2-pro', 'fenix-cl26r-pro', 'jackery-explorer-1000-v2', 'jackery-solarsaga-100w-air', 'midland-er310'];
const held = ['kidde-c3010-co-alarm', 'iniu-p62-20000mah-65w', 'jackery-explorer-300'];
const widths = [320, 375, 768, 1024, 1440, 1920];

test('production restores the authorized bunker while excluding product artwork, previews and affiliate activation', async ({ page, request, browser }) => {
  await page.goto('/');
  await expect(page.locator('.hero-image')).toBeVisible();
  await page.locator('.hero-image').evaluate((img: HTMLImageElement) => img.decode());
  await expect(page.locator('.hero-scene--neutral')).toHaveCount(0);
  const manifest = JSON.parse(readFileSync('src/data/media/manifest.json', 'utf8'));
  for (const asset of manifest.assets) for (const variant of asset.variants) {
    if (variant.src) expect((await request.get(variant.src)).status()).toBe(asset.id === 'hero' ? 200 : 404);
  }
  for (const slug of [...candidates, ...held]) {
    expect((await request.get(`/gear/${slug}/?view=release`)).status()).toBe(200);
    expect((await request.get(`/review/gear/${slug}/`)).status()).toBe(404);
  }
  for (const route of ['/review/gear/', '/review/blackout/']) expect((await request.get(route)).status()).toBe(404);
  await page.goto('/gear/?view=release');
  await expect(page.locator('article.card')).toHaveCount(8);
  await expect(page.locator('a[data-affiliate-click]')).toHaveCount(0);
  for (const slug of candidates) {
    await page.goto(`/gear/${slug}/`);
    await expect(page.getByText('Informational profile — verification in progress.')).toBeVisible();
    await expect(page.locator('.product-artwork--detail img')).toHaveCount(1);
    await expect(page.locator('a[data-affiliate-click]')).toHaveCount(0);
  }
  expect(await page.locator('body').innerText()).not.toMatch(/ChatGPT|Codex|AI-assisted|generated by AI/i);
  mkdirSync('.tools/qa/phase-3-5', { recursive: true });
  for (const width of [375, 1440]) {
    // Capture a fresh visit at each viewport, independent of prior navigation.
    const capture = await browser.newPage({ viewport: { width, height: 900 } });
    await capture.goto('http://127.0.0.1:4321/');
    await expect(capture.locator('.hero-image')).toBeInViewport();
    // decoding="async" can finish after load; inspect pixels only after decode.
    await capture.locator('.hero-image').evaluate((img: HTMLImageElement) => img.decode());
    await capture.screenshot({ path: `.tools/qa/phase-3-5/home-public-${width}.png`, fullPage: true });
    await capture.close();
  }
});

test('five candidate previews use approved illustrations and exclude commercial holds', async ({ page }) => {
  mkdirSync('.tools/qa/phase-3-5', { recursive: true });
  for (const route of ['/blackout/', '/gear/']) {
    await page.goto(`http://127.0.0.1:4322/review${route}`);
    await page.addStyleTag({ content: 'astro-dev-toolbar { display: none !important; }' });
    await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex, nofollow');
    await expect(page.locator('article.card')).toHaveCount(5);
    await expect(page.locator('.neutral-media')).toHaveCount(0);
    await expect(page.locator('article.card img')).toHaveCount(5);
    for (const slug of held) await expect(page.locator(`a[href*="/gear/${slug}/"]`)).toHaveCount(0);
    for (const slug of candidates) await expect(page.locator(`a[href="/review/gear/${slug}/"]`)).toHaveCount(1);
    for (const width of widths) {
      await page.setViewportSize({ width, height: 900 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
      if (route === '/gear/' && [375, 1440].includes(width)) {
        await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
        await page.screenshot({ path: `.tools/qa/phase-3-5/catalogue-preview-${width}.png`, fullPage: true, animations: 'disabled' });
      }
    }
  }
});

for (const slug of candidates) test(`${slug} release presentation remains private with documented facts and disabled links`, async ({ page }) => {
  const data = JSON.parse(readFileSync(`src/data/products/${slug}.json`, 'utf8'));
  await page.goto(`http://127.0.0.1:4322/review/gear/${slug}/`);
  await page.addStyleTag({ content: 'astro-dev-toolbar { display: none !important; }' });
  await expect(page.locator('main h1')).toHaveText(data.name);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', `https://apocalypsegearlab.github.io/gear/${slug}/`);
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex, nofollow');
  await expect(page.getByRole('link', { disabled: true })).toHaveCount(1);
  await expect(page.getByText('Amazon.ca links are pending confirmation of the Canadian listing and affiliate eligibility. No price, availability or seller is confirmed.')).toBeVisible();
  await expect(page.locator('.product-artwork--detail img')).toHaveCount(1);
  await expect(page.getByText('Not physically tested by us', { exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: `${data.name} specifications`, exact: true })).toBeVisible();
  expect(await page.locator('body').innerText()).not.toMatch(/ChatGPT|Codex|AI-assisted|owner-selected|Owner approval|Commercial use and source-photo permissions/i);
  for (const width of widths) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
    if (slug === 'jackery-explorer-1000-v2' && [375, 1440].includes(width)) {
      await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
      await page.screenshot({ path: `.tools/qa/phase-3-5/profile-preview-${width}.png`, fullPage: true, animations: 'disabled' });
    }
  }
});
